// Generates supabase/seed.sql from data/*.json so the CMS + plans start identical to the local content.
// Run: node scripts/gen-seed.mjs   (re-run after editing data/*.json; seed is idempotent: upserts)
import { readFileSync, writeFileSync } from "node:fs";

export const CMS_KEYS = ["site", "services", "configurator", "solutions", "cases", "process", "stack", "funnel", "testimonials", "pricing", "faq", "charts", "pages", "theme", "typography"];
const read = (k) => JSON.parse(readFileSync(`data/${k}.json`, "utf8"));
// Dollar-quoted literals: JSON can contain any quote character safely.
const lit = (s) => `$cms$${s}$cms$`;

const cms = CMS_KEYS.map((k) => `  ('${k}', ${lit(JSON.stringify(read(k)))}::jsonb, true)`).join(",\n");
const plans = read("plans")
  .map((p) => `  ('${p.id}', ${lit(p.name)}, '${p.region}', '${p.currency}', ${p.amount_minor}, '${p.interval}', ${p.gst_rate}, ${p.active}, ${p.sort})`)
  .join(",\n");

const sql = `-- Generated by scripts/gen-seed.mjs from data/*.json. Safe to re-run (upserts).

insert into public.cms_entries (key, value, published) values
${cms}
on conflict (key) do update set value = excluded.value, published = excluded.published, updated_at = now();

insert into public.plans (id, name, region, currency, amount_minor, interval, gst_rate, active, sort) values
${plans}
on conflict (id) do update set
  name = excluded.name, region = excluded.region, currency = excluded.currency, amount_minor = excluded.amount_minor,
  interval = excluded.interval, gst_rate = excluded.gst_rate, active = excluded.active, sort = excluded.sort, updated_at = now();

-- Make yourself an admin after signing up once at /login:
-- update public.profiles set role = 'admin' where email = 'you@example.com';
`;
writeFileSync("supabase/seed.sql", sql);
console.log(`seed.sql: ${CMS_KEYS.length} CMS entries, ${read("plans").length} plans`);
